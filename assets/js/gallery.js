function createPhotoButton(photo, className) {
  const button = document.createElement("button");
  button.type = "button";
  button.className = className;
  button.setAttribute("aria-label", `Open photo: ${photo.caption}`);

  const image = document.createElement("img");
  image.src = photoPath(photo);
  image.alt = photo.alt;
  image.loading = className === "featured-item" ? "eager" : "lazy";
  image.decoding = "async";
  button.append(image);

  const caption = document.createElement("span");
  caption.className = `${className}__caption`;
  const title = document.createElement("strong");
  title.textContent = photo.experience;
  const detail = document.createElement("span");
  detail.textContent = photo.caption;
  caption.append(title, detail);
  button.append(caption);
  return button;
}

function initGallery() {
  const grid = document.getElementById("galleryGrid");
  const featured = document.getElementById("featuredGallery");
  const filters = [...document.querySelectorAll(".filter-btn")];
  const loadMore = document.getElementById("galleryLoadMore");
  const count = document.getElementById("galleryCount");
  const lightbox = document.getElementById("lightbox");
  const lightboxImage = document.getElementById("lightboxImage");
  const lightboxCaption = document.getElementById("lightboxCaption");
  const lightboxExperience = document.getElementById("lightboxExperience");
  const lightboxCounter = document.getElementById("lightboxCounter");
  if (!grid || !featured || !lightbox) return;

  const pageSize = window.matchMedia("(max-width: 680px)").matches ? 12 : 18;
  let activeFilter = "all";
  let visibleCount = pageSize;
  let currentSet = [];
  let currentIndex = 0;
  let returnFocus = null;

  const filteredPhotos = () => activeFilter === "all"
    ? allPhotos
    : allPhotos.filter((photo) => photo.category === activeFilter);

  function renderGrid() {
    const photos = filteredPhotos();
    const fragment = document.createDocumentFragment();
    photos.slice(0, visibleCount).forEach((photo, index) => {
      const button = createPhotoButton(photo, "gallery-item");
      button.addEventListener("click", () => openLightbox(photos, index, button));
      fragment.append(button);
    });
    grid.replaceChildren(fragment);
    count.textContent = `${photos.length} photo${photos.length === 1 ? "" : "s"}`;
    loadMore.hidden = photos.length <= visibleCount;
  }

  function showImage(index) {
    currentIndex = (index + currentSet.length) % currentSet.length;
    const photo = currentSet[currentIndex];
    lightboxImage.src = photoPath(photo);
    lightboxImage.alt = photo.alt;
    lightboxCaption.textContent = photo.caption;
    lightboxExperience.textContent = photo.experience;
    lightboxCounter.textContent = `${currentIndex + 1} / ${currentSet.length}`;
  }

  function openLightbox(photos, index, trigger) {
    currentSet = photos;
    returnFocus = trigger;
    showImage(index);
    lightbox.hidden = false;
    document.body.style.overflow = "hidden";
    lightbox.querySelector(".lightbox-close").focus();
  }

  function closeLightbox() {
    lightbox.hidden = true;
    document.body.style.overflow = "";
    lightboxImage.removeAttribute("src");
    if (returnFocus?.isConnected) returnFocus.focus();
  }

  const featuredExperiences = [
    { category: "gaming", src: "gallery/letiarts-game-design-introduction.jpg", title: "Game design with LetiArts", kicker: "GAMING" },
    { category: "stem", src: "IMG-6685.jpg", title: "Hands-on STEM", kicker: "STEM" },
    { category: "vr", src: "gallery/child-trying-vr.jpg", title: "Trying virtual reality", kicker: "VR" },
  ];
  featuredExperiences.forEach((experience) => {
    const album = allPhotos.filter((photo) => photo.category === experience.category);
    const cover = allPhotos.find((photo) => photo.src === experience.src);
    const button = createPhotoButton(cover, "featured-item");
    button.querySelector(".featured-item__caption strong").textContent = experience.title;
    button.querySelector(".featured-item__caption span").textContent = experience.kicker;
    button.setAttribute("aria-label", `Open ${experience.title} photos`);
    button.addEventListener("click", () => openLightbox(album, album.indexOf(cover), button));
    featured.append(button);
  });

  filters.forEach((button) => button.addEventListener("click", () => {
    activeFilter = button.dataset.filter;
    visibleCount = pageSize;
    filters.forEach((filter) => filter.setAttribute("aria-pressed", String(filter === button)));
    renderGrid();
  }));
  loadMore.addEventListener("click", () => {
    visibleCount += pageSize;
    renderGrid();
  });

  lightbox.querySelector(".lightbox-close").addEventListener("click", closeLightbox);
  lightbox.querySelector(".lightbox-prev").addEventListener("click", () => showImage(currentIndex - 1));
  lightbox.querySelector(".lightbox-next").addEventListener("click", () => showImage(currentIndex + 1));
  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) closeLightbox();
  });
  document.addEventListener("keydown", (event) => {
    if (lightbox.hidden) return;
    if (event.key === "Escape") closeLightbox();
    if (event.key === "ArrowLeft") showImage(currentIndex - 1);
    if (event.key === "ArrowRight") showImage(currentIndex + 1);
  });
  let touchStartX = 0;
  lightbox.addEventListener("touchstart", (event) => {
    touchStartX = event.changedTouches[0].screenX;
  }, { passive: true });
  lightbox.addEventListener("touchend", (event) => {
    const distance = event.changedTouches[0].screenX - touchStartX;
    if (Math.abs(distance) > 50) showImage(currentIndex + (distance < 0 ? 1 : -1));
  }, { passive: true });

  renderGrid();
}

document.addEventListener("DOMContentLoaded", initGallery);
