function describeLegacyPhoto(photo) {
  const src = photo.src;
  if (src === "IMG_3855.JPG") {
    return { src, category: "gaming", experience: "Games and the people behind them", caption: "Meet the LetiArts team", alt: "LetiArts team at a Child-In-Tech event" };
  }
  if (src === "IMG_3854.JPG") {
    return { src, category: "vr", experience: "Trying virtual reality", caption: "Exploring VR at a CIT event", alt: "Visitor trying a VR headset at a Child-In-Tech event" };
  }
  if (stemPhotos.has(src)) {
    return { src, category: "stem", experience: "Hands-on STEM", caption: "STEM in action", alt: "Hands-on STEM activity at Child-In-Tech" };
  }
  if (codingPhotos.has(src)) {
    return { src, category: "coding", experience: "Coding together", caption: "Learning with technology", alt: "Children exploring technology in a Child-In-Tech session" };
  }
  const number = Number(src.match(/^IMG_(\d+)/)?.[1]);
  if (number >= 3824 && number <= 3841) {
    return { src, category: "events", experience: "Learning together", caption: "Children at a CIT session", alt: "Children at a Child-In-Tech learning session" };
  }
  if (number >= 3842 && number <= 3858) {
    return { src, category: "events", experience: "Tech conference", caption: "Exploring ideas at a CIT event", alt: "Activity at a Child-In-Tech conference" };
  }
  if (number >= 3859 && number <= 3873) {
    return { src, category: "events", experience: "Classroom discovery", caption: "A CIT learning session", alt: "Child-In-Tech classroom activity" };
  }
  if (number >= 3881 && number <= 3908) {
    return { src, category: "events", experience: "Tech visits and showcases", caption: "Exploring technology up close", alt: "Visit or showcase with Child-In-Tech" };
  }
  if (studentVoicePhotos.has(src)) {
    return { src, category: "events", experience: "Student voices", caption: "Children sharing what they learned", alt: "Children at a Child-In-Tech learning event" };
  }
  return { src, category: "events", experience: "CIT events", caption: "Children and technology in action", alt: "Moment from a Child-In-Tech event" };
}

